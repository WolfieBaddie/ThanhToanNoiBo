package com.example.thanhtoannoibo.DTO.Request.User;
import com.example.thanhtoannoibo.Common.UserType;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Data;

import java.util.Set;

@Data
public class CreateUserRequest {
    @NotBlank(message = "Tên đăng nhập không được để trống")
    @Size(min = 3, message = "Tên đăng nhập phải có ít nhất 3 ký tự")
    private String username;

    @NotBlank(message = "Mật khẩu không được để trống")
    @Size(min = 6, message = "Mật khẩu phải có ít nhất 6 ký tự")
    private String password;

    @NotBlank(message = "Email không được để trống")
    @Email(message = "Email không đúng định dạng")
    private String email;

    @NotBlank(message = "Họ tên không được để trống")
    private String fullName;

    private String phoneNumber;

    @NotNull(message = "Loại người dùng không được để trống")
    private UserType userType; // STUDENT, TEACHER, MERCHANT, ADMIN

    private Set<String> roles; // Danh sách mã quyền (VD: ["ADMIN", "MERCHANT"])
}